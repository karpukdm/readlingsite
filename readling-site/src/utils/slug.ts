/**
 * Русское склонение существительного после числа: 1 книга, 2 книги, 5 книг.
 *
 * Нужно везде, где число подставляется из данных: «83 книг» на странице
 * каталога читается как недосмотр, а такие мелочи и складываются в ощущение,
 * что страницу собрал автомат.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return few;
  return many;
}

export function extractSnippet(text: string, maxLen: number): string {
  const cleaned = text.replace(/\s+/g, ' ').trim();
  if (cleaned.length <= maxLen) return cleaned;
  const truncated = cleaned.slice(0, maxLen);
  const lastSentenceEnd = Math.max(
    truncated.lastIndexOf('. '),
    truncated.lastIndexOf('! '),
    truncated.lastIndexOf('? ')
  );
  if (lastSentenceEnd > maxLen * 0.5) {
    return truncated.slice(0, lastSentenceEnd + 1);
  }
  const lastSpace = truncated.lastIndexOf(' ');
  return (lastSpace > 0 ? truncated.slice(0, lastSpace) : truncated) + '…';
}

/**
 * Простой 32-bit хеш строки — для детерминированной "случайной" выборки.
 */
function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/**
 * Детерминированная "перетасовка" массива по seed-строке.
 * Используется для разнообразного, но стабильного отображения списка книг на странице.
 */
export function pickByHash<T extends { title: string }>(items: T[], count: number, seed: string): T[] {
  const sorted = [...items].sort((a, b) => toSlug(a.title).localeCompare(toSlug(b.title)));
  const scored = sorted.map((item, idx) => ({
    item,
    score: hashString(seed + ':' + toSlug(item.title) + ':' + idx),
  }));
  scored.sort((a, b) => a.score - b.score);
  return scored.slice(0, count).map(s => s.item);
}
